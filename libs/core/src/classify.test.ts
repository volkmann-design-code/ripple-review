import { describe, expect, it } from "vitest";
import { classify, generatedMatcher } from "./classify.ts";
import type { ChangedFile, LanguageAdapter, ModuleFacts } from "./model.ts";
import { MemorySnapshot } from "./snapshot.ts";

const isGenerated = await generatedMatcher(
  new MemorySnapshot({
    ".gitattributes": [
      "# comment",
      "*.gen.ts linguist-generated",
      "/libs/db/schema.dump.sql linguist-generated=true",
      "generated-docs/ linguist-generated",
      "libs/api/**/*.pb.go linguist-generated",
      "libs/api/keep.pb.go -linguist-generated",
      "file?.txt linguist-generated",
      "*.png binary",
      "",
    ].join("\n"),
  }),
);

describe("generatedMatcher (.gitattributes)", () => {
  it.each([
    ["x.gen.ts", true],
    ["deep/dir/x.gen.ts", true],
    ["x.gen.tsx", false],
    ["libs/db/schema.dump.sql", true],
    ["other/libs/db/schema.dump.sql", false],
    ["generated-docs/a/b.md", true],
    ["nested/generated-docs/b.md", true],
    ["libs/api/x.pb.go", true],
    ["libs/api/v1/deep/x.pb.go", true],
    ["libs/api/keep.pb.go", false],
    ["libs/apix/x.pb.go", false],
    ["file1.txt", true],
    ["file10.txt", false],
    ["logo.png", false],
  ])("%s → %s", (path, expected) => {
    expect(isGenerated(path)).toBe(expected);
  });

  it("matches nothing without a .gitattributes", async () => {
    const none = await generatedMatcher(new MemorySnapshot({}));
    expect(none("a.gen.ts")).toBe(false);
  });
});

describe("classify", () => {
  const file = (path: string): ChangedFile => ({
    path,
    status: "modified",
    additions: 1,
    deletions: 0,
    binary: false,
    hunks: [],
  });
  const role = (
    path: string,
    opts: {
      content?: string;
      facts?: ModuleFacts;
      adapter?: LanguageAdapter;
      generated?: boolean;
    } = {},
  ) =>
    classify(
      file(path),
      opts.content,
      opts.adapter,
      opts.facts,
      () => opts.generated ?? false,
    );
  const facts = (f: Partial<ModuleFacts>): ModuleFacts => ({
    imports: [],
    exports: [],
    reexports: [],
    definitions: [],
    ...f,
  });

  it.each([
    ["bun.lock", "lockfile"],
    ["apps/web/package-lock.json", "lockfile"],
    ["libs/db/src/generated/types.ts", "generated"],
    ["README.md", "docs"],
    ["apps/cli/fixtures/pr-1/expected.md", "test-support"],
    ["src/__snapshots__/a.test.ts.snap", "test-support"],
    ["pkg/testdata/input.json", "test-support"],
    ["docs/testing/guide.md", "docs"],
    ["libs/a/src/a.test.ts", "test"],
    ["libs/a/src/__tests__/a.ts", "test"],
    ["svc/handler_test.go", "test"],
    ["libs/test-utils/src/harness.ts", "test-support"],
    ["libs/a/src/__mocks__/x.ts", "test-support"],
    ["libs/a/package.json", "config"],
    ["tsconfig.base.json", "config"],
    [".github/workflows/ci.yml", "config"],
    ["libs/a/vitest.config.ts", "config"],
    ["vitest.shared.ts", "config"],
    ["nx.json", "config"],
    ["apps/x/project.json", "config"],
    ["lefthook.yml", "config"],
    ["renovate.json5", "config"],
    ["libs/a/src/vite-plugin.ts", "source"],
    ["libs/api/src/contracts/user.ts", "contract"],
    ["types/global.d.ts", "contract"],
    ["libs/a/src/a.ts", "source"],
  ])("%s → %s", (path, expected) => {
    expect(role(path)).toBe(expected);
  });

  it("uses .gitattributes and generated headers", () => {
    expect(role("a.ts", { generated: true })).toBe("generated");
    expect(role("a.ts", { content: "// @generated by tool\nexport {}" })).toBe(
      "generated",
    );
    expect(role("a.ts", { content: "/* DO NOT EDIT */" })).toBe("generated");
  });

  it("calls a file of a megabyte or more generated", () => {
    const big = `type Query {\n${"  field: String\n".repeat(70_000)}}`;
    expect(role("src/schema.graphql", { content: big })).toBe("generated");
    expect(role("src/a.ts", { content: "export const a = 1;" })).toBe("source");
  });

  it("keeps code in a fixtures directory as code", () => {
    const adapter = { roleHint: () => "schema" } as unknown as LanguageAdapter;
    expect(
      role("libs/db/migrations/fixtures/functions/f.sql", { adapter }),
    ).toBe("schema");
  });

  it("takes the adapter's hint after the path rules", () => {
    const adapter = {
      roleHint: () => "schema",
    } as unknown as LanguageAdapter;
    expect(role("db/migrations/1.sql", { adapter })).toBe("schema");
    expect(role("db/migrations/1.test.sql", { adapter })).toBe("test");
  });

  it("calls a file that only re-exports wiring", () => {
    const reexports = [{ specifier: "./a", names: "*" as const }];
    expect(role("libs/a/src/index.ts", { facts: facts({ reexports }) })).toBe(
      "wiring",
    );
    expect(
      role("libs/a/src/index.ts", {
        facts: facts({ reexports, exports: ["x"] }),
      }),
    ).toBe("source");
  });
});
