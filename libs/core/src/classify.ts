const LOCKFILES = new Set([
  "bun.lock",
  "bun.lockb",
  "package-lock.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "Cargo.lock",
  "go.sum",
  "poetry.lock",
  "uv.lock",
  "Gemfile.lock",
  "composer.lock",
  "Pipfile.lock",
  "flake.lock",
]);

const GENERATED_SIZE = 1_000_000;
const GENERATED_HEADER =
  /@generated|do not edit|auto-?generated|code generated by|generated by .{1,40}(?:do not|don't) edit/i;

/** Matcher for `linguist-generated` paths declared in the root .gitattributes. */
export async function generatedMatcher(
  head: Snapshot,
): Promise<(path: string) => boolean> {
  const text = (await head.read(".gitattributes")) ?? "";
  const rules: { re: RegExp; on: boolean }[] = [];
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) {
      continue;
    }
    const [pattern, ...attrs] = line.split(/\s+/);
    for (const a of attrs) {
      if (a === "linguist-generated" || a === "linguist-generated=true") {
        rules.push({ re: globToRegExp(pattern!), on: true });
      } else if (
        a === "-linguist-generated" ||
        a === "linguist-generated=false"
      ) {
        rules.push({ re: globToRegExp(pattern!), on: false });
      }
    }
  }
  return (path) => {
    let result = false;
    for (const r of rules) {
      if (r.re.test(path)) {
        result = r.on; // last match wins
      }
    }
    return result;
  };
}

function globToRegExp(glob: string): RegExp {
  const anchored = glob.includes("/") && !glob.endsWith("/");
  let g = glob.replace(/^\//, "");
  if (g.endsWith("/")) {
    g += "**";
  }
  let re = "";
  for (let i = 0; i < g.length; i++) {
    const c = g[i]!;
    if (c === "*" && g[i + 1] === "*") {
      re += ".*";
      i++;
      if (g[i + 1] === "/") {
        i++;
      }
    } else if (c === "*") {
      re += "[^/]*";
    } else if (c === "?") {
      re += "[^/]";
    } else {
      re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
    }
  }
  return new RegExp(anchored ? `^${re}$` : `(^|/)${re}$`);
}

const TEST_DIR = /(^|\/)(__tests__|tests?|specs?|e2e|integration-tests?)\//;
const TEST_FILE =
  /(\.|_)(test|spec)\.\w+$|(^|\/)test_[^/]+\.py$|_test\.go$|Tests?\.\w+$/;
const TEST_SUPPORT_SEGMENT =
  /^(test-?utils?|testing|test-?helpers?|test-?support|__mocks__|mocks?|.+-testing|.+-test-utils)$/;
/**
 * Test data and expected outputs, checked before the docs rule (a golden `.md`
 * is no doc). Only for files no adapter parses: code in such a directory is
 * still code (graphile-migrate keeps SQL functions in `migrations/fixtures/`).
 */
const FIXTURE_SEGMENT =
  /^(__fixtures__|fixtures?|__snapshots__|testdata|test-?data|golden)$/;
const DOC_EXT = /\.(md|mdx|rst|txt|adoc)$/i;
const CONFIG_FILE =
  /(^|\/)(package\.json|nx\.json|project\.json|turbo\.json|lefthook\.ya?ml|renovate\.json5?|\.editorconfig|(?:vitest|vite|jest|playwright)\.[^/]+\.[cm]?[jt]s|tsconfig[^/]*\.json|jsconfig\.json|\.gitattributes|\.gitignore|\.npmrc|\.nvmrc|Dockerfile[^/]*|docker-compose[^/]*\.ya?ml|[^/]+\.config\.[cm]?[jt]s|[^/]+\.config\.json|biome\.jsonc?|\.eslintrc[^/]*|\.prettierrc[^/]*|[^/]+\.toml|\.env[^/]*|Makefile)$|(^|\/)\.github\/.+\.ya?ml$/;
const CONTRACT_SEGMENT = /contract|^types?$|^interfaces?$|^api-?spec$|^proto$/i;

export function classify(
  file: ChangedFile,
  content: string | undefined,
  adapter: LanguageAdapter | undefined,
  facts: ModuleFacts | undefined,
  isGenerated: (path: string) => boolean,
): Role {
  const path = file.path;
  const base = path.slice(path.lastIndexOf("/") + 1);
  const segments = path.split("/").slice(0, -1);

  if (LOCKFILES.has(base)) {
    return "lockfile";
  }
  if (
    isGenerated(path) ||
    segments.some((s) => s === "generated" || s === "__generated__")
  ) {
    return "generated";
  }
  if (content && GENERATED_HEADER.test(content.slice(0, 600))) {
    return "generated";
  }
  // Nobody writes a megabyte by hand: schema dumps, introspection results,
  // generated clients.
  if (content && content.length >= GENERATED_SIZE) {
    return "generated";
  }
  if (!adapter && segments.some((s) => FIXTURE_SEGMENT.test(s))) {
    return "test-support";
  }
  if (DOC_EXT.test(path)) {
    return "docs";
  }
  if (TEST_DIR.test(path) || TEST_FILE.test(base)) {
    return "test";
  }
  if (segments.some((s) => TEST_SUPPORT_SEGMENT.test(s))) {
    return "test-support";
  }
  if (CONFIG_FILE.test(path)) {
    return "config";
  }
  const hint = adapter?.roleHint?.(path);
  if (hint) {
    return hint;
  }
  if (
    base.endsWith(".d.ts") ||
    segments.some((s) => CONTRACT_SEGMENT.test(s))
  ) {
    return "contract";
  }
  if (facts && facts.exports.length === 0 && facts.reexports.length > 0) {
    return "wiring";
  }
  return "source";
}

/** Lower comes first among files that are otherwise equal. */
export const ROLE_RANK: Record<Role, number> = {
  docs: 0,
  schema: 1,
  contract: 2,
  source: 3,
  wiring: 4,
  config: 5,
  "test-support": 6,
  test: 7,
  generated: 8,
  lockfile: 9,
};
